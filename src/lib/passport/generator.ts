import { RunCostPassport } from "@/types/passport";
import { PreflightReport, ProposedPatch } from "@/types/runguard";
import { FinOpsComparisonResult, FinOpsCalculationResult } from "@/types/finops";
import { NebiusDiagnosticResult } from "../nebius/client";
import { EvidenceCitation } from "@/types/passport";

export interface BuildPassportOptions {
  projectName: string;
  targetGpu: string;
  gpuCount: number;
  preflightReport: PreflightReport;
  diagnosticResult?: {
    success: boolean;
    modelUsed: string;
    rawText?: string;
    parsedResponse?: {
      likelyRootCause: string;
      alternativeExplanations?: string[];
      actionPlan?: string[];
    };
  };
  citations?: EvidenceCitation[];
  finopsComparison?: FinOpsComparisonResult;
  fallbackFinops?: FinOpsCalculationResult;
  proposedPatch?: ProposedPatch;
}

export function generateRunCostPassport(options: BuildPassportOptions): RunCostPassport {
  const timestamp = new Date().toISOString();
  const id = `rcp-${Date.now()}`;

  const nebiusModel = options.diagnosticResult?.modelUsed || process.env.NEBIUS_MODEL || "nvidia/Llama-3.1-Nemotron-70B-Instruct-HF";
  const baseUrl = (process.env.NEBIUS_BASE_URL || "https://api.tokenfactory.nebius.com/v1").replace(/\/+$/, "");

  // Finops summary mapping
  const baselineCost = options.finopsComparison
    ? options.finopsComparison.baseline.totalCostUsd
    : options.fallbackFinops?.totalCostUsd || 0;
  
  const proposedCost = options.finopsComparison
    ? options.finopsComparison.proposed.totalCostUsd
    : baselineCost;

  const deltaSavings = options.finopsComparison
    ? options.finopsComparison.deltaCostUsd
    : 0;

  const percentageSavings = options.finopsComparison
    ? options.finopsComparison.percentageDifference
    : 0;

  const assumptions = options.finopsComparison
    ? [...options.finopsComparison.baseline.assumptions, ...options.finopsComparison.proposed.assumptions]
    : options.fallbackFinops?.assumptions || ["Baseline workload estimates."];

  const priceSources = options.finopsComparison
    ? options.finopsComparison.baseline.priceSources
    : options.fallbackFinops?.priceSources || [];

  // Diagnostic investigation assembly
  let diagnosticInvestigation;
  if (options.diagnosticResult && options.diagnosticResult.success && options.diagnosticResult.parsedResponse) {
    diagnosticInvestigation = {
      modelUsed: options.diagnosticResult.modelUsed,
      querySummary: "Sanitized runtime failure and cluster config analysis",
      likelyRootCause: options.diagnosticResult.parsedResponse.likelyRootCause,
      alternativeExplanations: options.diagnosticResult.parsedResponse.alternativeExplanations || [],
      confidenceAssessment: "Reasoning generated by NVIDIA Nemotron model based on sanitized execution trace. Requires independent deterministic verification before deployment.",
      citations: options.citations || [],
      sanitizedLogSample: "[Log sanitized: secrets redacted]",
      diagnosticTimestamp: timestamp,
    };
  }

  // Audit trail
  const auditTrail: RunCostPassport["auditTrail"] = [
    {
      step: "DETERMINISTIC_PREFLIGHT",
      actor: "SYSTEM_DETERMINISTIC",
      timestamp,
      details: `Evaluated ${options.preflightReport.checks.length} static and runtime checks. Overall status: ${options.preflightReport.overallStatus}`,
    },
  ];

  if (options.diagnosticResult) {
    auditTrail.push({
      step: "NEBIUS_NVIDIA_DIAGNOSTIC",
      actor: "NEBIUS_NVIDIA_LLM",
      timestamp,
      details: `Queried ${nebiusModel} via Nebius Token Factory with sanitized trace. Success: ${options.diagnosticResult.success}`,
    });
  }

  if (options.citations && options.citations.length > 0) {
    auditTrail.push({
      step: "TAVILY_EVIDENCE_RETRIEVAL",
      actor: "TAVILY_SEARCH",
      timestamp,
      details: `Retrieved ${options.citations.length} verified technical documentation citations.`,
    });
  }

  if (options.proposedPatch) {
    auditTrail.push({
      step: "PATCH_LIFECYCLE",
      actor: options.proposedPatch.status === "APPROVED" || options.proposedPatch.status === "APPLIED" ? "USER_APPROVAL" : "SYSTEM_DETERMINISTIC",
      timestamp: options.proposedPatch.approvedAt || timestamp,
      details: `Patch '${options.proposedPatch.title}' status is ${options.proposedPatch.status}. Target: ${options.proposedPatch.targetFile}`,
    });
  }

  return {
    id,
    schemaVersion: "1.0.0",
    title: `Run & Cost Passport — ${options.projectName}`,
    createdAt: timestamp,
    targetEnvironment: {
      projectName: options.projectName,
      targetGpu: options.targetGpu,
      gpuCount: options.gpuCount,
      nebiusModel,
      sanitizedBaseUrl: baseUrl,
    },
    overallRunGuardStatus: options.preflightReport.overallStatus,
    preflightChecks: options.preflightReport.checks,
    diagnosticInvestigation,
    proposedPatch: options.proposedPatch || options.preflightReport.suggestedPatch,
    finopsSummary: {
      baselineCostUsd: baselineCost,
      proposedCostUsd: proposedCost,
      deltaSavingsUsd: deltaSavings,
      percentageSavings,
      isSavingsVerified: options.finopsComparison ? options.finopsComparison.isSavingsVerified : (options.fallbackFinops?.isPriceVerified ?? false),
      savingsClassification: options.finopsComparison ? options.finopsComparison.savingsClassification : (options.fallbackFinops?.isPriceVerified ? "VERIFIED_PUBLISHED" : "UNVERIFIED_ESTIMATE"),
      assumptions,
      priceSources,
    },
    unresolvedRisks: options.preflightReport.unresolvedRisks,
    auditTrail,
  };
}

